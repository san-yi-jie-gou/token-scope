const supportedLanguages = Object.keys(translations);
const aliases = {
  zh: "zh-Hans",
  "zh-CN": "zh-Hans",
  "zh-SG": "zh-Hans",
  "zh-Hans": "zh-Hans",
  ja: "ja",
  ko: "ko",
  es: "es",
  en: "en"
};

function normalizeLanguage(language) {
  if (!language) return "en";
  if (aliases[language]) return aliases[language];
  const base = language.split("-")[0];
  return aliases[base] || "en";
}

function preferredLanguage() {
  const requested = new URLSearchParams(window.location.search).get("lang");
  const normalizedRequest = normalizeLanguage(requested);
  if (requested && supportedLanguages.includes(normalizedRequest)) return normalizedRequest;

  const saved = localStorage.getItem("tokenscope-language");
  if (saved && supportedLanguages.includes(saved)) return saved;
  const browserLanguages = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
  return browserLanguages.map(normalizeLanguage).find((language) => supportedLanguages.includes(language)) || "en";
}

function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = language;
  document.title = dictionary["meta.title"];
  document.getElementById("meta-description").setAttribute("content", dictionary["meta.description"]);
  document.getElementById("og-description").setAttribute("content", dictionary["meta.ogDescription"]);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute("aria-label", value);
  });

  const selector = document.getElementById("language-select");
  selector.value = language;
  localStorage.setItem("tokenscope-language", language);
}

document.addEventListener("DOMContentLoaded", () => {
  const selector = document.getElementById("language-select");
  applyLanguage(preferredLanguage());
  selector.addEventListener("change", (event) => applyLanguage(event.target.value));
});
